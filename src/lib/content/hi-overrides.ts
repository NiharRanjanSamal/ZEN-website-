function deepMerge<T extends PlainObject>(base: T, overrides: PlainObject): T {
  const out = { ...base } as PlainObject;
  for (const [key, value] of Object.entries(overrides)) {
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      out[key] &&
      typeof out[key] === "object" &&
      !Array.isArray(out[key])
    ) {
      out[key] = deepMerge(out[key] as PlainObject, value as PlainObject);
    } else {
      out[key] = value;
    }
  }
  return out as T;
}

type PlainObject = Record<string, unknown>;

export function applyHiOverrides<T extends PlainObject>(content: T): T {
  return deepMerge(content, hiOverrides as PlainObject);
}
